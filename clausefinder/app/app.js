async function boot() {
  applyTheme(LS.get('theme', 'dark'));
  S.scope = LS.get('scope', 'book');
  bindGlobal();
  progress(20);

  if (location.protocol === 'file:') {
    $('#doc').innerHTML = `<div class="welcome">
      <div class="w-badge" style="color:var(--warn);background:rgba(245,158,11,.12);border-color:rgba(245,158,11,.35)">Wrong way in</div>
      <h2>Start ClauseFinder with its launcher</h2>
      <p>Opening <code>index.html</code> straight from the file system leaves the browser unable to read the
      rule data next to it. Close this tab and double-click <b>ClauseFinder.bat</b> in the same folder instead.</p></div>`;
    progress(100); return;
  }
  try {
    // Online the CDN caches every object for a year - right for the immutable
    // book files, wrong for the registry once a book is added. dataVersion in
    // cf-config bumps the URL so a new registry is fetched; per-book files are
    // new keys anyway.
    S.books = await getJSON(dataUrl('books.json' + (CFG.dataVersion ? '?v=' + CFG.dataVersion : '')));
    if (!Array.isArray(S.books) || !S.books.length) throw new Error('empty');
  } catch (e) {
    $('#doc').innerHTML = `<div class="welcome">
      <div class="w-badge" style="color:var(--warn);background:rgba(245,158,11,.12);border-color:rgba(245,158,11,.35)">No data</div>
      <h2>The rule data has not been built yet</h2>
      <p>Run <code>node build/build.js</code> in the ClauseFinder folder, then reload.</p></div>`;
    progress(100); return;
  }

  const wanted = LS.get('book', null);
  const b = S.books.find(x => x.id === wanted) || S.books[0];
  await setBook(b.id);
  progress(100);
  route();
  window.addEventListener('hashchange', route);

  // warm every index while the reader is idle — search spans all books
  const warm = () => Promise.all(S.books.map(x => ensureIndex(x.id).catch(() => {})));
  if (typeof requestIdleCallback === 'function') requestIdleCallback(warm, { timeout: 5000 });
  else setTimeout(warm, 1500);
}

async function ensureBook(id) {
  if (S.lib.has(id)) return S.lib.get(id);
  const meta = S.books.find(b => b.id === id);
  const data = await getJSON(dataUrl(`${id}/toc.json`));
  const secMap = new Map(), secList = [];
  for (const p of data.toc)
    for (const c of p.chapters)
      for (const s of c.sections) {
        const rec = { ...s, part: p, chap: c, book: meta };
        secMap.set(s.id, rec); secList.push(rec);
      }
  secList.sort((a, b) => a.order - b.order);
  const entry = { meta, toc: data.toc, secMap, secList, clauses: null, figures: null };
  S.lib.set(id, entry);
  return entry;
}

// Concurrent callers share one download; a failure clears the slot so the next
// call retries instead of leaving that book silently missing from every search.
const inflight = new Map();
function ensureIndex(id) {
  const done = S.lib.get(id);
  if (done && done.clauses) return Promise.resolve(done);
  if (inflight.has(id)) return inflight.get(id);
  const p = (async () => {
    const e = await ensureBook(id);
    if (e.clauses) return e;
    const [cl, fg] = await Promise.all([
      getJSON(dataUrl(`${id}/search.json`)),
      getJSON(dataUrl(`${id}/figures.json`)).catch(() => [])
    ]);
    for (const c of cl) { c.lt = c.t.toLowerCase(); c.b = id; }
    e.clauses = cl;
    e.figures = fg.map(f => ({ ...f, b: id, ll: (f.l + ' ' + (f.t || '')).toLowerCase() }));
    return e;
  })();
  p.catch(() => {}).then(() => inflight.delete(id));
  inflight.set(id, p);
  return p;
}
/* The picker works in two steps: pick the class society, then pick among the
   books we actually hold for that class. */
const societyOf = b => b.society || (b.code || '').split(/[-\s]/)[0].toUpperCase();
const societies = () => [...new Set(S.books.map(societyOf))];
const booksOf = soc => S.books.filter(b => societyOf(b) === soc);

/* Search and Ask read this, not the whole library: answering a DNV question out of
   an LR clause is worse than not answering, and a 5-book pool dilutes the top-k. */
function scopedBooks() {
  if (S.scope === 'all' || !S.book) return S.books;
  if (S.scope === 'node' && S.scopeNode) return S.books.filter(b => b.id === S.scopeNode.book);
  if (S.scope === 'society') return booksOf(societyOf(S.book));
  return S.books.filter(b => b.id === S.book.id);
}

/* A Set of section ids when the scope is narrowed to one part or chapter of the
   tree, null when the whole book (or more) is in play.  Kept separate from
   scopedBooks so every retriever can apply it the same way. */
function scopedSections() {
  return S.scope === 'node' && S.scopeNode ? S.scopeNode.set : null;
}

/* Collect the sections under a part, or under one chapter of it. */
function sectionsUnder(bookId, partId, chapId) {
  const e = S.lib.get(bookId); if (!e) return [];
  const out = [];
  for (const p of e.toc) {
    if (p.id !== partId) continue;
    for (const c of p.chapters) {
      if (chapId && c.id !== chapId) continue;
      for (const sec of c.sections) out.push(sec.id);
    }
  }
  return out;
}

function clearNodeScope() {
  S.scope = 'book'; S.scopeNode = null;
  LS.set('scope', 'book'); LS.set('scopeNode', null);
  renderScope(); renderTree($('#navFilter') ? $('#navFilter').value : '');
  toast('Searching ' + (S.book ? S.book.short : 'this book') + ' again');
}

/* Scope can be a part, a chapter or a single section - the same machinery, only
   the set of sections differs. */
function applyNodeScope(bookId, id, secs, label, saved) {
  if (!secs.length) return false;
  S.scope = 'node';
  S.scopeNode = { book: bookId, id, label, secs, set: new Set(secs) };
  LS.set('scope', 'node');
  LS.set('scopeNode', Object.assign({ book: bookId, label }, saved));
  renderScope();
  toast('Searching ' + label + ' only — ' + secs.length + ' section' + (secs.length > 1 ? 's' : ''));
  return true;
}

function setNodeScope(bookId, partId, chapId, label) {
  return applyNodeScope(bookId, chapId || partId, sectionsUnder(bookId, partId, chapId), label,
                        { part: partId, chap: chapId || '' });
}

function setSectionScope(bookId, secId, label) {
  return applyNodeScope(bookId, secId, [secId], label, { sec: secId });
}

