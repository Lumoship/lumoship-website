function hl(text, q) {
  if (!q) return esc(text);
  const i = String(text).toLowerCase().indexOf(q);
  if (i < 0) return esc(text);
  return esc(text.slice(0, i)) + '<mark>' + esc(text.slice(i, i + q.length)) + '</mark>' + esc(text.slice(i + q.length));
}

/* ══════════════════════════════ query engine ══════════════════════════════ */

const NUM_RE = /^\d+(\.\d+){0,4}\.?$/;

function parseQuery(raw, whole) {
  const phrases = [], excl = [];
  let rest = String(raw || '');
  rest = rest.replace(/-"([^"]+)"/g, (m, p) => { excl.push(p.toLowerCase().trim()); return ' '; });
  rest = rest.replace(/"([^"]+)"/g, (m, p) => { phrases.push(p.toLowerCase().trim()); return ' '; });
  rest = rest.replace(/(^|\s)-([^\s]+)/g, (m, sp, w) => { excl.push(w.toLowerCase()); return ' '; });
  const tokens = rest.toLowerCase().split(/[^a-z0-9µΔσετ°.\-_/]+/i).filter(t => t.length > 1);
  const nums = tokens.filter(t => NUM_RE.test(t)).map(t => t.replace(/\.$/, ''));
  const words = tokens.filter(t => !NUM_RE.test(t));
  const terms = [...phrases, ...words];
  return { raw: String(raw || '').trim(), phrases, words, nums, excl, terms, whole: !!whole,
           empty: !phrases.length && !words.length && !nums.length };
}

// every position where any term occurs, merged and sorted
function findHits(lt, q) {
  const out = [];
  for (const t of q.terms) {
    if (!t) continue;
    let i = 0;
    while ((i = lt.indexOf(t, i)) !== -1) {
      const okL = !q.whole || i === 0 || !/[a-z0-9]/.test(lt[i - 1]);
      const okR = !q.whole || i + t.length >= lt.length || !/[a-z0-9]/.test(lt[i + t.length]);
      if (okL && okR) out.push([i, t.length]);
      i += Math.max(1, t.length);
      if (out.length > 400) break;
    }
  }
  out.sort((a, b) => a[0] - b[0]);
  const merged = [];
  for (const h of out) {
    const last = merged[merged.length - 1];
    if (last && h[0] <= last[0] + last[1]) last[1] = Math.max(last[1], h[0] + h[1] - last[0]);
    else merged.push(h.slice());
  }
  return merged;
}

function scoreClause(c, q) {
  if (q.excl.some(x => c.lt.includes(x))) return null;
  let sc = 0, numHit = false;
  for (const n of q.nums) {
    if (c.n === n) { sc += 400; numHit = true; }
    else if (c.n && c.n.startsWith(n + '.')) { sc += 120; numHit = true; }
    else if (c.lt.includes(n)) sc += 8;
  }
  const hits = q.terms.length ? findHits(c.lt, q) : [];
  if (q.phrases.length) {
    for (const p of q.phrases) if (!c.lt.includes(p)) return null;
    sc += 90 * q.phrases.length;
  }
  if (q.words.length) {
    let miss = 0;
    for (const w of q.words) {
      const i = c.lt.indexOf(w);
      if (i < 0) { miss++; continue; }
      sc += 16 + (i < 110 ? 8 : 0);
    }
    if (miss === q.words.length && !numHit) return null;
    if (!miss) sc += 40;                       // all words present
    else if (!numHit && miss > 0 && q.words.length > 1) sc -= miss * 22;
  }
  if (!hits.length && !numHit) return null;
  sc += Math.min(hits.length, 6) * 4;
  if (c.h) sc += 10;                            // headings rank a little higher
  sc += proximityBonus(c.lt, q.words);          // terms sitting together beat terms scattered
  return { c, sc, hits };
}

// smallest window containing one occurrence of every word — tight windows score much higher
function proximityBonus(lt, words) {
  if (words.length < 2) return 0;
  const pos = words.map(w => {
    const a = []; let i = 0;
    while ((i = lt.indexOf(w, i)) !== -1) { a.push(i); i += w.length; if (a.length > 60) break; }
    return a;
  });
  if (pos.some(a => !a.length)) return 0;
  const idx = pos.map(() => 0);
  let best = Infinity;
  for (;;) {
    let mn = Infinity, mx = -1, mi = 0;
    for (let k = 0; k < pos.length; k++) {
      const v = pos[k][idx[k]];
      if (v < mn) { mn = v; mi = k; }
      if (v > mx) mx = v;
    }
    best = Math.min(best, mx - mn);
    if (++idx[mi] >= pos[mi].length) break;
  }
  return best <= 70 ? 90 : best <= 180 ? 45 : best <= 400 ? 15 : 0;
}

async function runSearch(q, filters) {
  if (q.empty) return { groups: [], total: 0, facets: null };
  for (let attempt = 0; attempt < 2 && !allIndexed(); attempt++)
    await Promise.all(missingBooks().map(b => ensureIndex(b.id).catch(() => {})));
  const pending = missingBooks();

  const raw = [];
  for (const b of S.books) {
    const e = S.lib.get(b.id); if (!e || !e.clauses) continue;
    for (const c of e.clauses) {
      const r = scoreClause(c, q);
      if (r) raw.push(r);
    }
  }

  // facet counts are computed before filtering so the numbers stay meaningful
  const fBook = new Map(), fPart = new Map(), fType = new Map();
  const bump = (m, k, lbl) => { const o = m.get(k) || { k, lbl, n: 0 }; o.n++; m.set(k, o); };
  const decorate = r => {
    const e = S.lib.get(r.c.b);
    r.sec = e.secMap.get(r.c.s);
    return r.sec;
  };
  for (const r of raw) {
    if (!decorate(r)) continue;
    bump(fBook, r.c.b, S.lib.get(r.c.b).meta.short);
    bump(fPart, r.c.b + '|' + r.sec.part.id, r.sec.part.label + ' ' + (r.sec.part.title || ''));
    bump(fType, r.c.h ? 'heading' : 'clause', r.c.h ? 'Headings' : 'Clauses');
  }

  const keep = raw.filter(r => r.sec
    && (!filters.book.size || filters.book.has(r.c.b))
    && (!filters.part.size || filters.part.has(r.c.b + '|' + r.sec.part.id))
    && (!filters.type.size || filters.type.has(r.c.h ? 'heading' : 'clause')));

  // group by section
  const gm = new Map();
  for (const r of keep) {
    const k = r.c.b + '|' + r.c.s;
    let g = gm.get(k);
    if (!g) { g = { key: k, book: S.lib.get(r.c.b).meta, sec: r.sec, hits: [], top: 0 }; gm.set(k, g); }
    g.hits.push(r);
    if (r.sc > g.top) g.top = r.sc;
  }
  const groups = [...gm.values()];
  for (const g of groups) {
    g.hits.sort((a, b) => cmpClause(a.c.n, b.c.n));
    // a section whose own title carries the query is almost always what was wanted
    const hay = (g.sec.label + ' ' + (g.sec.chap.title || '') + ' ' + (g.sec.part.title || '')).toLowerCase();
    let tb = 0;
    for (const w of q.words) if (hay.includes(w)) tb += 55;
    if (q.words.length > 1 && q.words.every(w => hay.includes(w))) tb += 170;
    if (q.words.length > 1 && hay.includes(q.words.join(' '))) tb += 260;
    for (const p of q.phrases) if (hay.includes(p)) tb += 260;
    g.titleBoost = tb;
    g.score = g.top + tb + Math.min(g.hits.length, 8) * 4;
  }
  if (filters.sort === 'doc') {
    const bi = id => S.books.findIndex(b => b.id === id);
    groups.sort((a, b) => bi(a.book.id) - bi(b.book.id) || a.sec.order - b.sec.order);
  } else {
    groups.sort((a, b) => b.score - a.score || a.sec.order - b.sec.order);
  }
  return { groups, total: keep.length, allTotal: raw.length, pending,
           facets: { book: [...fBook.values()], part: [...fPart.values()].sort((a, b) => b.n - a.n),
                     type: [...fType.values()] } };
}

function cmpClause(a, b) {
  const pa = String(a || '').split('.').map(Number), pb = String(b || '').split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const x = pa[i] || 0, y = pb[i] || 0;
    if (x !== y) return x - y;
  }
  return String(a).localeCompare(String(b));
}

/* ── sentence-aware context ───────────────────────────────────────── */

const SENT_END = /[.;:!?]\s/g;
function sentenceWindow(text, at, len, before = 1, after = 1) {
  let start = 0, end = text.length;
  // walk back over `before` sentence boundaries
  let idx = at, found = 0;
  while (idx > 0 && found <= before) {
    const cut = lastBoundary(text, idx);
    if (cut < 0) { start = 0; break; }
    found++; idx = cut;
    if (found > before) { start = cut; break; }
    start = cut;
  }
  idx = at + len; found = 0;
  while (idx < text.length && found <= after) {
    SENT_END.lastIndex = idx;
    const m = SENT_END.exec(text);
    if (!m) { end = text.length; break; }
    found++; idx = m.index + m[0].length; end = idx;
    if (found > after) break;
  }
  if (at - start > 320) start = at - 320;
  if (end - (at + len) > 340) end = at + len + 340;
  return [Math.max(0, start), Math.min(text.length, end)];
}
function lastBoundary(text, from) {
  for (let i = from - 2; i > 0; i--) {
    if (/[.;:!?]/.test(text[i]) && /\s/.test(text[i + 1])) return i + 2;
  }
  return -1;
}

// renders the clause text with every hit marked, cropped to a readable window
function contextHtml(text, hits) {
  if (!hits.length) return esc(text.slice(0, 260)) + (text.length > 260 ? ' …' : '');
  const [s0, e0] = sentenceWindow(text, hits[0][0], hits[0][1]);
  let s = s0, e = e0;
  for (const h of hits) {                       // stretch to cover nearby hits too
    if (h[0] < e + 220 && h[0] + h[1] > e) e = Math.min(text.length, h[0] + h[1] + 140);
  }
  let out = '', pos = s;
  for (const [i, l] of hits) {
    if (i + l <= s || i >= e) continue;
    if (i > pos) out += esc(text.slice(pos, i));
    out += '<mark>' + esc(text.slice(i, i + l)) + '</mark>';
    pos = i + l;
  }
  out += esc(text.slice(pos, e));
  return (s > 0 ? '<span class="lead">… </span>' : '') + out + (e < text.length ? '<span class="tail"> …</span>' : '');
}

