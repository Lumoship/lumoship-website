async function setBook(id) {
  const e = await ensureBook(id);
  S.book = e.meta;
  LS.set('book', id);
  S.recent = LS.get('recent.' + id, []);

  if (S.scope === 'node' && (!S.scopeNode || S.scopeNode.book !== id)) { S.scope = 'book'; S.scopeNode = null; }
  S.society = societyOf(e.meta);
  $('#classCode').textContent = S.society;
  $('#classPick').title = e.meta.publisher;
  $('#bookCode').textContent = e.meta.code;
  $('#bookName').textContent = `${e.meta.short} · ${e.meta.edition}`;
  $('#brandSub').textContent = `${e.meta.publisher} — ${e.meta.title}`;
  $('#chipStats').textContent = `${e.meta.sections} sections · ${e.meta.clauses.toLocaleString('en')} clauses`;
  document.title = `ClauseFinder — ${e.meta.short}`;
  // a branch scope saved from a previous session only makes sense once the
  // book's contents tree is loaded, so it is restored here rather than at boot
  if (S.scope === 'node' && !S.scopeNode) {
    const saved = LS.get('scopeNode', null);
    if (saved && saved.book === id) {
      const secs = saved.sec ? (e.secMap.has(saved.sec) ? [saved.sec] : [])
                             : sectionsUnder(saved.book, saved.part, saved.chap || '');
      if (secs.length) S.scopeNode = { book: saved.book, id: saved.sec || saved.chap || saved.part,
                                       label: saved.label, secs, set: new Set(secs) };
    }
    if (!S.scopeNode) S.scope = 'book';
  }
  renderScope();
  renderTree();
  return e;
}
