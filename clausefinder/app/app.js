function expandGroup(key) {
  const g = SV.res.groups.find(x => x.key === key); if (!g) return;
  const box = $(`.grp[data-g="${CSS.escape(key)}"] .grp-hits`); if (!box) return;
  let html = '';
  for (const r of g.hits) {
    const i = SV.flat.length;
    SV.flat.push({ b: g.book.id, s: g.sec.id, a: r.c.a });
    html += `<button class="hit" data-i="${i}">
      <span class="hit-no${r.c.h ? ' head' : ''}">${esc(r.c.n || (r.c.h ? '§' : '¶'))}</span>
      <span class="hit-body">${contextHtml(r.c.t, r.hits)}${
        r.hits.length > 1 ? `<span class="hit-more">${r.hits.length} occurrences in this clause</span>` : ''}</span>
    </button>`;
  }
  box.innerHTML = html;
  box.closest('.grp').classList.add('open');
}

